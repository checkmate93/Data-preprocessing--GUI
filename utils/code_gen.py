"""Build a runnable pipeline.py from the recipe."""

import inspect
import re

from utils.ops import helpers

HELPER_NAMES = [
    name for name, obj in vars(helpers).items()
    if callable(obj) and getattr(obj, "__module__", "") == helpers.__name__
]
HELPER_CONSTANTS = [name for name in vars(helpers) if name.isupper()]


def _used_helpers(code):
    """Helpers named in the snippets (called, or passed as a function like map_text(df, cols, strip_accents)),
    plus every helper those helpers use (transitively)."""
    found = {name for name in HELPER_NAMES if re.search(rf"\b{name}\b", code)}
    queue = list(found)
    while queue:
        source = inspect.getsource(getattr(helpers, queue.pop()))
        for name in HELPER_NAMES:
            if name not in found and re.search(rf"\b{name}\b", source):
                found.add(name)
                queue.append(name)
    return [name for name in HELPER_NAMES if name in found]  # keep file order


def read_expression(meta):
    """pandas expression that reads a file with the settings detected at upload (source or attachment)."""
    path = repr(meta["filename"])
    fmt = meta["format"]
    if fmt == "csv":
        text_columns = meta.get("text_columns") or []
        dtype = f", dtype={ {c: 'string' for c in text_columns}!r}" if text_columns else ""
        return (f"pd.read_csv({path}, encoding={meta.get('encoding')!r}, "
                f"sep={meta.get('delimiter')!r}, decimal={meta.get('decimal')!r}{dtype}, low_memory=False)")
    if fmt == "excel":
        return f"pd.read_excel({path}, sheet_name={meta.get('sheet') or 0!r})"
    if fmt == "json":
        return f"pd.json_normalize(json.load(open({path}, encoding={meta.get('encoding') or 'utf-8'!r})))"
    if fmt == "jsonl":
        return f"pd.read_json({path}, lines=True)"
    return f"pd.read_{fmt}({path})"


def _read_line(source):
    return f"df = {read_expression(source)}"


def build_script(source, steps):
    """source: shared["source"]; steps: active recipe steps (each has label + code)."""
    body = "\n".join(step["code"] for step in steps)
    used = _used_helpers(body)
    lines = [
        '"""Generated by DataPrep Studio.',
        f"Source file: {source['filename']}",
        f"Steps: {len(steps)}",
        '"""',
        "",
        "import json",
        "import re",
        "import unicodedata",
        "import warnings",
        "",
        "import numpy as np",
        "import pandas as pd",
    ]
    if "snake_case_name" in used:
        lines.append("from unidecode import unidecode")
    if used:
        lines += ["", ""]
        constants_needed = [c for c in HELPER_CONSTANTS if any(
            re.search(rf"\b{c}\b", inspect.getsource(getattr(helpers, name))) for name in used)]
        for constant in constants_needed:
            lines.append(f"{constant} = {getattr(helpers, constant)!r}")
        for name in used:
            lines += ["", "", inspect.getsource(getattr(helpers, name)).rstrip()]
    lines += ["", "", "def run():", f"    {_read_line(source)}"]
    for number, step in enumerate(steps, start=1):
        lines.append("")
        lines.append(f"    # {number}. {step['label']}")
        for code_line in step["code"].splitlines():
            lines.append(f"    {code_line}" if code_line else "")
    lines += [
        "    return df",
        "",
        "",
        'if __name__ == "__main__":',
        "    result = run()",
        "    print(result.shape)",
        "    result.to_csv('cleaned.csv', index=False, encoding='utf-8-sig')",
        "",
    ]
    return "\n".join(lines)
